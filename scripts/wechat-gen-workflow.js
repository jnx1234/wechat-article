// 标题重排区：标题原文 + 断行版（逗号留在行尾，成果后缀括号单独成块）
const titleBlock = (title) => {
  const t = title.trim();
  const m = t.match(/^(.*?)(（[^）]*）)\s*$/);      // 拆出结尾的成果后缀
  const main = (m ? m[1] : t).trim();
  const tag = m ? m[2].trim() : '';
  const segs = main.split(/(?<=，)/).map(s => s.trim()).filter(Boolean); // 逗号后断行
  const parts = tag ? [...segs, tag] : segs;
  return parts.length > 1 ? `${t}\n\n${parts.join('\n\n')}` : t;
};

